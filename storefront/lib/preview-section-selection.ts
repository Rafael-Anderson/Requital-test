// The theme builder's section selection, as the preview receives it. The admin is the source of
// truth for what is selected (the tree and a click in the preview both end up there), so the
// preview only draws what the admin last sent: `preview-select-section` with a section id (or null
// for "nothing selected"), the section's display name for the chip and the builder's accent colour.
// The preview asks for the current selection with `preview-selection-request` when it mounts,
// because a message sent before its listener existed (a page navigation inside the iframe) is lost.

export const SELECT_SECTION_MESSAGE = "preview-select-section";
export const SELECTION_REQUEST_MESSAGE = "preview-selection-request";

export interface PreviewSectionSelection {
  sectionId: string;
  label: string;
  color: string;
}

const HEX_COLOR = /^#[0-9a-fA-F]{3,8}$/;
const FALLBACK_COLOR = "#0f766e";
// Section ids are generated by the builder; anything else is not ours to look up in the DOM.
const SECTION_ID = /^[A-Za-z0-9_-]{1,100}$/;

/**
 * Reads a `preview-select-section` message. Returns null for "clear the outline", a selection to
 * draw, or undefined when the message is not this one or is malformed (ignored, nothing changes).
 */
export function parseSectionSelectMessage(data: unknown): PreviewSectionSelection | null | undefined {
  if (!data || typeof data !== "object") return undefined;
  const d = data as Record<string, unknown>;
  if (d.type !== SELECT_SECTION_MESSAGE) return undefined;
  if (d.sectionId === null) return null;
  if (typeof d.sectionId !== "string" || !SECTION_ID.test(d.sectionId)) return undefined;
  const label = typeof d.label === "string" ? d.label.trim().slice(0, 60) : "";
  const color = typeof d.color === "string" && HEX_COLOR.test(d.color.trim()) ? d.color.trim() : FALLBACK_COLOR;
  return { sectionId: d.sectionId, label, color };
}

/** A section's box in the iframe's viewport, rounded, for the theme-section-selected message. */
export function sectionRect(el: Element): { top: number; left: number; width: number; height: number } {
  const r = el.getBoundingClientRect();
  return { top: Math.round(r.top), left: Math.round(r.left), width: Math.round(r.width), height: Math.round(r.height) };
}
